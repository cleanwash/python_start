# [실습] 놀이공원 입장료 계산기

#1. 나이를 입력하세요
age = int(input('나이를 입력하세요: '))

#2. 요금 계산기 
if age <8 :
    print('미취학 아동입니다')
    price = 0
elif age >=60:
    print('경로 우대입니다')
    price = 0
elif age<14:
    print('초등학생입니다')
    price = 2000
else:
    print('일반인입니다')
    price = 5000

#결과 출력
print(f'입장료는 {price}원 입니다')


'''
- 파이썬 변수 = 이름표. 어떤 저장공간(스코프/네임스페이스, 딕셔너리 같은 것)에 "이름 → 실제 객체 주소"로 등록되는 것뿐이야.
- if/elif/else/for/while은 그 저장공간을 새로 만들지 않아. 그냥 흐름을 나누는 갈림길일 뿐, 원래 있던 바깥 저장공간(지금은 모듈 전체, globals())에 그대로 등록돼.
- 그래서 if 블록 "안"에서 price = 5000이 실행되면, price라는 이름표가 if 블록에 갇히는 게 아니라 바로 globals()에 박제돼서, if가 끝난 뒤에도 그 스코프(모듈 전체) 어디서든 접근 가능한 거야.
- 진짜로 새 저장공간(스코프)을 만드는 건 def(함수), class, lambda 뿐 — 이것들 안에서 만든 변수만 바깥에서 안 보여.
'''