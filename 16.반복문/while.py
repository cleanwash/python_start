'''
[실습 목표]
1. while 문의 기본 구조 이해하기 (조건이 참일 동안 반복)
2. 반복 횟수를 세는 변수 활용하기 (i = i + 1)
3. 사용자 입력에 따라 반복 종료하기
'''

# 1. while 문 기초: 나무 찍기 (열 번 찍어 안 넘어가는 나무 없다)
hit = 0  # 찍은 횟수 (초기값)

# 조건: 10번 미만일 때 계속 반복
while hit < 10:
    hit = hit + 1  # 횟수 증가 (이거 없으면 무한 루프!)
    print(f"나무를 {hit}번 찍었습니다.")

    if hit == 10:
        print("나무가 넘어갑니다! 쿵!")

print("-" * 30)

# 2. 조건 반복: 스무고개 (특정 값이 될 때까지)
# 사용자가 "exit"라고 칠 때까지 계속 물어봅니다.

user_input = ""  # 초기화 (빈 문자열)

while user_input != "exit":
    print("현재 실행 중... (종료하려면 exit 입력)")
    user_input = input("명령어 입력: ")
    print(f"입력하신 명령: {user_input}")

print("프로그램을 종료합니다.")