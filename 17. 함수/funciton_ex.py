# -------------------------------------------------
# 1. 함수 정의 (Define) - 레시피 적기
# -------------------------------------------------
# def 키워드를 사용합니다. (아직 실행은 안 됩니다!)
def make_burger():
    print("--- 🍔 햄버거 만들기 ---")
    print("1. 빵을 굽는다.")
    print("2. 패티를 올린다.")
    print("3. 야채와 소스를 뿌린다.")
    print("4. 완성! 맛있게 드세요.")

# -------------------------------------------------
# 2. 함수 호출 (Call) - 주문하기
# -------------------------------------------------
print("주방장님, 햄버거 하나 주세요!")
make_burger()  # 여기서 위 코드가 실행됩니다.

print("\n(잠시 후...)")

print("주방장님, 여기 햄버거 추가요!")
make_burger()  # 또 필요하면 이름만 부르면 됩니다. (재사용)

print("-" * 30)

# -------------------------------------------------
# 3. [비교] 함수가 없을 때 (노가다)
# -------------------------------------------------
# 햄버거를 3개 만들어야 한다면?
print("--- 😱 함수 없이 만들기 ---")

